#!/bin/bash
set -o errexit

# Installs Docker Engine and lays down the Kestra compose stack + systemd unit.
# Does NOT start Kestra: the basic-auth password is generated per-Droplet by
# the cloud-init first-boot script in files/var/lib/cloud/scripts/per-instance/,
# so every image build must not embed a shared secret.

install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc

echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu \
  $(. /etc/os-release && echo "$VERSION_CODENAME") stable" | tee /etc/apt/sources.list.d/docker.list > /dev/null

apt-get -qqy update
apt-get -qqy install docker-ce docker-ce-cli containerd.io docker-compose-plugin
systemctl enable docker

mkdir -p /opt/kestra
cat > /opt/kestra/docker-compose.yml <<EOF
volumes:
  kestra-data:
    driver: local
  kestra-postgres-data:
    driver: local

services:
  postgres:
    image: postgres:16-alpine
    restart: always
    volumes:
      - kestra-postgres-data:/var/lib/postgresql/data
    environment:
      POSTGRES_DB: kestra
      POSTGRES_USER: kestra
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U kestra"]
      interval: 5s
      timeout: 5s
      retries: 10

  kestra:
    image: kestra/kestra:${kestra_version}
    restart: always
    depends_on:
      postgres:
        condition: service_healthy
    user: "root"
    command: server standalone --worker-thread=128
    volumes:
      - kestra-data:/app/storage
      - /var/run/docker.sock:/var/run/docker.sock
      - /tmp/kestra-wd:/tmp/kestra-wd
    environment:
      KESTRA_CONFIGURATION: |
        datasources:
          postgres:
            url: jdbc:postgresql://postgres:5432/kestra
            driverClassName: org.postgresql.Driver
            username: kestra
            password: \${POSTGRES_PASSWORD}
        kestra:
          server:
            basic-auth:
              enabled: true
              username: "\${KESTRA_ADMIN_USERNAME}"
              password: "\${KESTRA_ADMIN_PASSWORD}"
          repository:
            type: postgres
          storage:
            type: local
            local:
              base-path: "/app/storage"
          queue:
            type: postgres
          tasks:
            tmp-dir:
              path: /tmp/kestra-wd/tmp
          url: http://localhost:8080/
    ports:
      - "8080:8080"
      - "8081:8081"
EOF

cat > /etc/systemd/system/kestra.service <<'EOF'
[Unit]
Description=Kestra OSS (docker compose)
Requires=docker.service
After=docker.service network-online.target
Wants=network-online.target

[Service]
WorkingDirectory=/opt/kestra
EnvironmentFile=/opt/kestra/.env
ExecStart=/usr/bin/docker compose up
ExecStop=/usr/bin/docker compose down
Restart=always

[Install]
WantedBy=multi-user.target
EOF

# Not enabled here: /opt/kestra/.env doesn't exist yet (the per-Droplet
# secrets are generated by the cloud-init first-boot script), so starting
# this unit now would race against that script. It enables+starts kestra.service
# itself once .env is written.
